namespace KeyboardWtf.Tests;

using KeyboardWtf.Services.Connectors;
using Xunit;

public sealed class ConnectorConversationalFollowupIntentTests
{
    [Theory]
    [InlineData("Give me more details on that.")]
    [InlineData("Could give me more details on that conversation.")]
    [InlineData("Can show me the full conversation?")]
    [InlineData("Would tell me more about that email?")]
    [InlineData("Tell me about this.")]
    [InlineData("Explain that.")]
    [InlineData("Could you please give me more information about that email?")]
    [InlineData("Tell me the details of that thread.")]
    [InlineData("Can you give me a detailed summary of that conversation?")]
    [InlineData("Yes, please read the full conversation.")]
    [InlineData("Tell me more about that email please.")]
    [InlineData("Show me the entire conversation.")]
    [InlineData("Pull up the details.")]
    [InlineData("Please pull up the full details of that thread.")]
    [InlineData("What is that email about?")]
    [InlineData("What is the subject of that email?")]
    [InlineData("What did she say in that email?")]
    [InlineData("Could you please tell me what she asked for?")]
    [InlineData("What was the latest message in that thread?")]
    [InlineData("Did I reply to that email?")]
    [InlineData("Yeah sure give me more details.")]
    [InlineData("Yeah, sure, give me more details about the email which I had sent.")]
    [InlineData("Give me more details about the one I sent.")]
    [InlineData("Get more details about that email.")]
    [InlineData("Give me the detail.")]
    [InlineData("Can you give me more details on that email?")]
    [InlineData("Give me more details about the thread you found.")]
    [InlineData("Give me details about the email you just read.")]
    [InlineData("Tell me about it.")]
    [InlineData("Provide more details about the entire conversation history.")]
    [InlineData("Get the full conversation history.")]
    [InlineData("Pull up the entire conversation history.")]
    [InlineData("Could you please provide more details about the full conversation history?")]
    [InlineData("Yeah sure tell me about that thread.")]
    public void Natural_anaphoric_reads_are_details_followups(string request)
        => Assert.True(ConnectorFollowupIntent.MailDetails(request));

    [Theory]
    [InlineData("Yes, please.")]
    [InlineData("Yes please do.")]
    [InlineData("Sure, go ahead.")]
    [InlineData("Okay, please do.")]
    [InlineData("Go ahead please.")]
    [InlineData("Yeah sure.")]
    [InlineData("Yeah, sure, please.")]
    [InlineData("Yes okay please do.")]
    public void Concise_read_offer_acceptance_is_recognized(string request)
        => Assert.True(ConnectorFollowupIntent.Affirmative(request));

    [Theory]
    [InlineData("I found the conversation. Would you like more information?")]
    [InlineData("Would you like me to provide more details?")]
    [InlineData("Would you like me to read out the full conversation?")]
    [InlineData("Shall I give you a detailed summary of that thread?")]
    [InlineData("Do you want me to tell you more about that email?")]
    [InlineData("Should I pull up the complete thread for you?")]
    [InlineData("Would you like a summary")]
    [InlineData("Would you like to see more details?")]
    [InlineData("I found the conversation. Is there anything specific you'd like to know about these emails?")]
    [InlineData("Is there something else you would like to know about that thread?")]
    [InlineData("I found the conversation. Is there a specific detail you were looking for?")]
    [InlineData("Is there a particular detail you are looking for")]
    [InlineData("Is there any specific detail you'd like to know more about?")]
    [InlineData("Would you like me to read any particular message in more detail?")]
    [InlineData("Would you like to know more about any of these messages?")]
    [InlineData("Would you like me to look into any specific part of that thread?")]
    [InlineData("Is there anything specific you'd like to know from that thread?")]
    [InlineData("Is there anything else about these emails you'd like to know?")]
    [InlineData("Is there anything specific you wanted to focus on within that summary?")]
    [InlineData("Would you like details on any specific email from that thread?")]
    [InlineData("Would you like me to read any specific message or give more detail?")]
    [InlineData("Would you like me to provide more details or read a particular email?")]
    [InlineData("Is there anything else you'd like to know about them?")]
    [InlineData("I found the conversation. I can read the full messages if you like.")]
    [InlineData("I could also read the full messages if you'd like.")]
    [InlineData("I can provide more details if you want.")]
    [InlineData("Do you want me to attempt to retrieve more details?")]
    [InlineData("Would you like me to try to read the full messages?")]
    [InlineData("Would you like me to read the most recent one?")]
    [InlineData("Would you like me to read the latest email?")]
    public void Natural_details_offer_is_retained_even_without_asr_question_mark(string answer)
        => Assert.True(ConnectorFollowupIntent.OffersMailDetails(answer));

    [Theory]
    [InlineData("Yes, send a reply.")]
    [InlineData("Yes, open that email.")]
    [InlineData("Yes, cancel the search.")]
    [InlineData("Give me details and send a reply.")]
    [InlineData("Pull up the details and send a reply.")]
    [InlineData("Read that thread then open Gmail.")]
    [InlineData("Read that email and delete it.")]
    [InlineData("Find the email with Sophia Gao and give me more details.")]
    [InlineData("Give me details about another email.")]
    [InlineData("Tell me more about the weather.")]
    [InlineData("Show me my calendar.")]
    [InlineData("What is 2 + 2?")]
    [InlineData("Open Gmail.")]
    [InlineData("Give me the detail and delete that email.")]
    [InlineData("Give me details on another email.")]
    [InlineData("Tell me about the weather.")]
    [InlineData("Yeah sure send that reply.")]
    [InlineData("Explain this selected text.")]
    [InlineData("Give me more details on that and delete it.")]
    [InlineData("Tell me about this other email.")]
    [InlineData("Give me more details on that in another account.")]
    public void Another_goal_or_compound_action_does_not_borrow_read_authority(string request)
    {
        Assert.False(ConnectorFollowupIntent.MailDetails(request));
        Assert.False(ConnectorFollowupIntent.Affirmative(request));
    }

    [Theory]
    [InlineData("Yeah sure give me more details about the email which I had sent.", ConnectorMailSelection.Sent)]
    [InlineData("Read the one I sent.", ConnectorMailSelection.Sent)]
    [InlineData("Give me details about the email that I received.", ConnectorMailSelection.Received)]
    [InlineData("Read the email I sent and delete it.", ConnectorMailSelection.Unspecified)]
    [InlineData("Find the email I sent.", ConnectorMailSelection.Unspecified)]
    public void Selected_mail_read_is_separate_from_the_execution_task(string request, object selection)
        => Assert.Equal((ConnectorMailSelection)selection, ConnectorFollowupIntent.MailSelection(request));

    [Theory]
    [InlineData("Would you like me to send a reply?")]
    [InlineData("Would you like me to open that conversation?")]
    [InlineData("Would you like more details or should I send a reply?")]
    [InlineData("Should I retrieve the details and delete the email?")]
    [InlineData("Would you like information about another email?")]
    [InlineData("The sender asked whether you want me to send the messages.")]
    [InlineData("Is there anything specific you'd like to know about these emails or should I send a reply?")]
    [InlineData("Is there anything specific you'd like to know about another email?")]
    [InlineData("Would you like me to send a reply? Is there anything specific you'd like to know about these emails?")]
    [InlineData("Is there a specific detail you were looking for in another email?")]
    [InlineData("Is there any specific detail you'd like to know more about another email?")]
    [InlineData("Is there a specific detail you were looking for or should I send a reply?")]
    [InlineData("Would you like me to send a reply? Is there a specific detail you were looking for?")]
    [InlineData("Would you like me to read any particular message in more detail and send a reply?")]
    [InlineData("Would you like to know more about any of these messages or delete them?")]
    [InlineData("Would you like to know more about another message?")]
    [InlineData("Would you like me to look into any specific part of another thread?")]
    [InlineData("Would you like me to look into any specific part of that thread and send a reply?")]
    [InlineData("Is there anything specific you'd like to know from that thread or should I delete it?")]
    [InlineData("Is there anything else about another email you'd like to know?")]
    [InlineData("Is there anything else about these emails you'd like to know or should I send a reply?")]
    [InlineData("Is there anything specific you wanted to focus on within that summary and delete?")]
    [InlineData("Would you like details on any specific email from another thread?")]
    [InlineData("Would you like details on any specific email from that thread or should I send a reply?")]
    [InlineData("Would you like me to read any specific message or send a reply?")]
    [InlineData("Would you like me to read any specific message or give more detail and delete it?")]
    [InlineData("Would you like me to read any specific message or give more detail about another thread?")]
    [InlineData("Is there anything else you'd like to know about them or should I send a reply?")]
    [InlineData("I can send a reply if you like.")]
    [InlineData("I can open the messages if you like.")]
    [InlineData("I can read the full messages and delete them if you like.")]
    [InlineData("I can read the full messages about another thread if you like.")]
    [InlineData("I can send a reply if you like. Would you like more details?")]
    [InlineData("Would you like me to send a reply? I can read the messages if you like.")]
    [InlineData("I can read the full messages if you like, then send a reply.")]
    [InlineData("I can read the messages, but I have not offered a next action.")]
    [InlineData("Do you want me to attempt to send a reply?")]
    [InlineData("Would you like me to try to read the messages and then delete them?")]
    [InlineData("Would you like me to try to retrieve more details about another thread?")]
    [InlineData("Would you like me to attempt to retrieve details or send a reply?")]
    [InlineData("Would you like me to attempt to send a reply? Would you like more details?")]
    [InlineData("Would you like me to attempt to try to read the messages?")]
    [InlineData("Would you like me to read the most recent one or send a reply?")]
    [InlineData("Would you like me to read the latest email from someone else?")]
    public void Other_or_ambiguous_offers_do_not_authorize_a_read(string answer)
        => Assert.False(ConnectorFollowupIntent.OffersMailDetails(answer));

    [Theory]
    [InlineData("Could you open it in a new tab and tell me more about what we discussed?")]
    [InlineData("Could you please give me a recap of the conversation and open it in a new tab?")]
    [InlineData("Open that conversation and explain the significance of the last message.")]
    [InlineData("Could you please recap all the details in that email conversation and open it again?")]
    [InlineData("Recap that conversation and open it again.")]
    [InlineData("Open that thread and recap the discussion in that conversation.")]
    public void Compound_contextual_read_uses_shared_read_intent(string request)
    {
        Assert.True(ConnectorFollowupIntent.TryReadAndOpen(request, out var read, out var open));
        Assert.True(ConnectorFollowupIntent.IsContextualReadRequest(read));
        Assert.True(ConnectorFollowupIntent.IsExactOpen(open));
    }

    [Theory]
    [InlineData("Open it and tell me about the weather.")]
    [InlineData("Open it and tell me why it rains.")]
    [InlineData("Open it and give me a recap of another email.")]
    [InlineData("Open it and could you find emails from Bob.")]
    [InlineData("Open it and read my work account.")]
    [InlineData("Open it and summarize that document.")]
    [InlineData("Read it and open Gmail.")]
    [InlineData("Read it and open both conversations.")]
    [InlineData("Open it and give details, then send a reply.")]
    [InlineData("Open it and describe the message from Bob.")]
    [InlineData("Open it and describe the conversation in another account.")]
    [InlineData("Open it and describe the message received today.")]
    [InlineData("Open it and could you not read the conversation.")]
    [InlineData("Open it and recap another email.")]
    [InlineData("Open it and recap the conversation in another account.")]
    [InlineData("Recap that conversation and forward it to Bob.")]
    public void Compound_read_rejects_unrelated_targets_scope_and_actions(string request)
        => Assert.False(ConnectorFollowupIntent.TryReadAndOpen(request, out _, out _));
}
